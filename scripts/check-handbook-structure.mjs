import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sidebars from '../config/sidebars.js'

const handbookRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const docsRoot = path.join(handbookRoot, 'docs')
const metadataSchemaDir = path.join(docsRoot, 'reference/jsonschema/metadata')

const requiredFiles = [
  'llms.txt',
  'llms-full.txt',
  'docs/ai/index.md',
  'docs/ai/terminology.md',
  'docs/ai/routing-hints.md',
  'docs/ai/task-recipes.md',
  'docs/ai/reference-sources.md',
]

const errors = []

for (const rel of requiredFiles) {
  if (!fs.existsSync(path.join(handbookRoot, rel))) {
    errors.push(`missing required handbook AI file: ${rel}`)
  }
}

for (const fileName of ['llms.txt', 'llms-full.txt']) {
  const rootFile = path.join(handbookRoot, fileName)
  const staticFile = path.join(handbookRoot, 'static', fileName)
  if (!fs.existsSync(staticFile)) {
    errors.push(`missing static AI entrypoint: static/${fileName}`)
  } else if (fs.existsSync(rootFile)) {
    const rootText = fs.readFileSync(rootFile, 'utf8')
    const staticText = fs.readFileSync(staticFile, 'utf8')
    if (rootText !== staticText) {
      errors.push(`static/${fileName} is out of sync with ${fileName}; run npm run sync:llms-static`)
    }
  }
}

const docs = []
function walkDocs(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue
    const filePath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      walkDocs(filePath)
    } else if (/\.mdx?$/.test(entry.name)) {
      docs.push(path.relative(docsRoot, filePath).replaceAll(path.sep, '/').replace(/\.mdx?$/, ''))
    }
  }
}
walkDocs(docsRoot)

const referenced = new Set()
function addAutogenerated(dirName) {
  for (const docId of docs) {
    if (docId === `${dirName}/index` || docId.startsWith(`${dirName}/`)) {
      referenced.add(docId)
    }
  }
}
function visit(item) {
  if (typeof item === 'string') {
    referenced.add(item)
    return
  }
  if (!item || typeof item !== 'object') return
  if (item.type === 'autogenerated' && item.dirName) addAutogenerated(item.dirName)
  if (item.link?.type === 'doc' && item.link.id) referenced.add(item.link.id)
  if (Array.isArray(item.items)) item.items.forEach(visit)
}
Object.values(sidebars).flat().forEach(visit)

const orphanDocs = docs.filter((docId) => !referenced.has(docId))
const missingDocs = [...referenced].filter((docId) => !docs.includes(docId))
if (orphanDocs.length) errors.push(`docs missing from sidebars: ${orphanDocs.join(', ')}`)
if (missingDocs.length) errors.push(`sidebar references missing docs: ${missingDocs.join(', ')}`)

const metadataSchemaIndexPath = path.join(metadataSchemaDir, 'index.json')
if (!fs.existsSync(metadataSchemaIndexPath)) {
  errors.push('missing metadata schema index: docs/reference/jsonschema/metadata/index.json')
} else {
  const metadataSchemaIndex = JSON.parse(fs.readFileSync(metadataSchemaIndexPath, 'utf8'))
  const entries = metadataSchemaIndex.entries || []
  if (!entries.length) errors.push('metadata schema index has no entries')
  const schemaFiles = fs
    .readdirSync(metadataSchemaDir)
    .filter((fileName) => fileName.endsWith('.schema.json'))
  if (entries.length !== schemaFiles.length) {
    errors.push(`metadata schema count mismatch: index=${entries.length}, files=${schemaFiles.length}`)
  }
  for (const entry of entries) {
    const schemaPath = path.join(metadataSchemaDir, entry.schema)
    if (!fs.existsSync(schemaPath)) {
      errors.push(`missing metadata schema file: ${entry.schema}`)
    } else {
      JSON.parse(fs.readFileSync(schemaPath, 'utf8'))
    }
  }
}

if (errors.length) {
  console.error(errors.map((error) => `- ${error}`).join('\n'))
  process.exit(1)
}

console.log(`Handbook structure OK: ${docs.length} docs, ${referenced.size} sidebar references`)
